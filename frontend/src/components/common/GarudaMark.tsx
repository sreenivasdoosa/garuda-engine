/**
 * The Garuda marks.
 *
 * Garuda is the eagle Lord Venkateshwara rides, so the mark is an eagle with
 * its wings spread. There are three cuts of it because one drawing cannot
 * survive the whole size range: layered flight feathers are the point of the
 * hero and turn to mush below about 40px, so the small cut replaces them with
 * one solid scalloped wing.
 *
 * They are inline rather than `<img src="/logo.svg">` so the wordmark's text
 * follows `currentColor` and works on the dark sign-in page and the console
 * chrome without a second file. `useId` keeps the gradient ids unique when two
 * marks share a page.
 */

interface MarkProps {
  className?: string;
  /** Rendered height in px. Width follows the mark's own aspect. */
  height?: number;
  title?: string;
}

